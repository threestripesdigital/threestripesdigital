import fs from 'node:fs';
import assert from 'node:assert/strict';
const root = new URL('../', import.meta.url);
const stateFile = new URL('ops/appointment-email-live.json', root);
const state = fs.existsSync(stateFile) ? JSON.parse(fs.readFileSync(stateFile)) : {tags:{},boost:{},website:{}};
const save = () => fs.writeFileSync(stateFile, JSON.stringify(state,null,2)+'\n');
const days=['monday','tuesday','wednesday','thursday','friday','saturday','sunday'];
async function api(path,method='GET',body) {
  for(let n=0;n<8;n++) {
    const r=await fetch('https://api.kit.com/v4/'+path,{method,headers:{'X-Kit-Api-Key':process.env.KIT_API_KEY,'Content-Type':'application/json'},body:body?JSON.stringify(body):undefined});
    if(r.status===429){await new Promise(resolve=>setTimeout(resolve,15000));continue;}
    const d=await r.json();if(!r.ok)throw Error(path+' '+r.status+' '+JSON.stringify(d));return d;
  }throw Error('Kit rate limit');
}
for(const [key,name] of Object.entries({managed:'rb_appointment_managed',stop:'rb_appointment_cutoff'})) {
  if(!state.tags[key]){state.tags[key]=(await api('tags','POST',{name})).tag.id;save();}
}
const fields=(await api('custom_fields')).custom_fields;
if(!fields.some(f=>f.key==='rank_boost_booking_link')) await api('custom_fields','POST',{label:'Rank Boost Booking Link'});
const qualified=JSON.parse(fs.readFileSync(new URL('ops/qualified-sequence-draft.json',root)));
const website=JSON.parse(fs.readFileSync(new URL('ops/downsell-email-system.json',root)));
const definitions={boost:qualified.emails.map(e=>({...e,key:e.key})),website:[...website.sequences.precall.emails.map((e,i)=>({...e,key:'W'+i})),...website.sequences.precall.rotation_pool.map((e,i)=>({...e,key:'P'+i})),{...website.sequences.tomorrow.emails[0],key:'R01'},{...website.sequences.soon.emails[0],key:'R02'}]};
for(const [offer,emails] of Object.entries(definitions))for(const e of emails) {
  const target=state[offer][e.key] ||= {};
  const exclusions=offer==='boost'?[22494650,22511246,22622480,23211559,state.tags.stop]:[23211442,23211443,23217408,23217410,23217411,23217412,22494644,22511246,state.tags.stop];
  if(!target.id){target.id=(await api('sequences','POST',{name:`Rank Boost appointment ${offer} ${e.key}`,email_address:website.email_address,email_template_id:website.template_id,active:false,repeat:true,hold:false,send_days:days,send_hour:9,time_zone:'America/New_York',exclude_subscriber_sources:[{type:'tag',ids:exclusions}]})).sequence.id;save();}
  const found=(await api(`sequences/${target.id}/emails?include_content=true`)).emails;
  const desired={subject:e.subject,content:e.content,delay_value:0,delay_unit:'hours',position:0,email_template_id:website.template_id,published:true};
  if(!found.length)target.email_id=(await api(`sequences/${target.id}/emails`,'POST',desired)).email.id;
  else {assert.equal(found.length,1);assert.equal(found[0].subject,e.subject);assert.equal(found[0].content,e.content);target.email_id=found[0].id;}
  target.verified=true;save();console.log('Verified',offer,e.key);
}
if(process.argv.includes('--activate')) {
  // Preserve every existing exclusion; add permanent migration suppression.
  for(const id of [2862371,2887690,2887691,2887692,2887771,2887775,2887776]) {
    const seq=(await api('sequences/'+id)).sequence;
    const sources=seq.exclude_subscriber_sources||[];
    const tags=sources.find(s=>s.type==='tag');
    if(tags)tags.ids=[...new Set([...tags.ids,state.tags.managed])];
    else sources.push({type:'tag',ids:[state.tags.managed]});
    await api('sequences/'+id,'PUT',{exclude_subscriber_sources:sources});
  }
  for(const offer of ['boost','website'])for(const target of Object.values(state[offer])) {
    assert.equal((await api('sequences/'+target.id,'PUT',{active:true})).sequence.active,true);target.active=true;save();
  }
}
fs.writeFileSync(new URL('functions/api/_appointmentconfig.js',root),'// Verified Kit resources. Generated by install-appointment-emails.mjs.\nexport const APPOINTMENT_EMAILS = '+JSON.stringify(state,null,2)+';\n');
console.log('Appointment email resources verified. Activation:',process.argv.includes('--activate'));
